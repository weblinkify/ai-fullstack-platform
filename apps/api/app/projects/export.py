import re

from app.projects.models import ProjectResponse


def _bullet_list(items: list[str]) -> str:
    if not items:
        return "- None specified"

    return "\n".join(f"- {item}" for item in items)


def _numbered_list(items: list[str]) -> str:
    if not items:
        return "No implementation plan provided."

    return "\n".join(f"{index}. {item}" for index, item in enumerate(items, 1))


def architecture_filename(title: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")

    return f"{slug or 'nexora-project'}-architecture.md"


def build_architecture_document(project: ProjectResponse) -> str:
    architecture = project.architecture

    return f"""# {project.title}

## Executive Summary

{project.summary}

---

## Product Capabilities

{_bullet_list(project.features)}

---

## System Architecture

### Frontend

{_bullet_list(architecture.frontend)}

### Backend

{_bullet_list(architecture.backend)}

### Data Layer

{_bullet_list(architecture.database)}

### Infrastructure

{_bullet_list(architecture.infrastructure)}

---

## API Surface

{_bullet_list(project.api)}

---

## Data Model

{_bullet_list(project.database)}

---

## Implementation Plan

{_numbered_list(project.implementation_plan)}

---

## Generated by Nexora AI

This architecture document was generated by Nexora AI from the original product requirements.
"""
